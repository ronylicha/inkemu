//! Renders the register list as the Rust source of `svd-regs`' `esp32c3.rs`.
use crate::expand::Register;

const HALF_WORD_BITS: u32 = 16;
const HALF_WORD_MASK: u32 = 0xFFFF;

/// `0x60000000` -> `0x6000_0000`: `clippy::unreadable_literal` is on in the workspace.
fn hex32(value: u32) -> String {
    format!(
        "0x{:04x}_{:04x}",
        value >> HALF_WORD_BITS,
        value & HALF_WORD_MASK
    )
}

fn register_line(register: &Register) -> String {
    format!(
        "    RegisterInfo {{ addr: {}, peripheral: {:?}, name: {:?}, reset_value: {}, reset_explicit: {} }},\n",
        hex32(register.addr),
        register.peripheral,
        register.name,
        hex32(register.reset_value),
        register.reset_explicit,
    )
}

/// One line per register, so that a regenerated file diffs readably.
/// `source_name` is the repository-relative path of the SVD, `source_sha256` its digest.
pub fn emit(source_name: &str, source_sha256: &str, registers: &[Register]) -> String {
    let mut out = format!(
        "// @generated by `cargo run -p svd-gen` from {source_name}\n\
         // (sha256 {source_sha256}). Do not edit.\n\
         // Register data: Copyright Espressif Systems (Shanghai) Co., Ltd., Apache-2.0 (espressif/svd).\n\
         use crate::RegisterInfo;\n\
         \n\
         pub(crate) static REGISTERS: [RegisterInfo; {}] = [\n",
        registers.len()
    );
    for register in registers {
        out.push_str(&register_line(register));
    }
    out.push_str("];\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::expand::Register;

    #[test]
    fn emitted_file_pins_header_array_length_and_register_lines() {
        let regs = [
            Register {
                addr: 0x6000_0000,
                peripheral: "UART0".into(),
                name: "FIFO".into(),
                reset_value: 0,
                reset_explicit: false,
            },
            Register {
                addr: 0x6000_001C,
                peripheral: "UART0".into(),
                name: "STATUS".into(),
                reset_value: 0xE000_C000,
                reset_explicit: true,
            },
        ];
        let out = emit("third_party/espressif-svd/esp32c3.svd", "abc123", &regs);
        let expected = "\
// @generated by `cargo run -p svd-gen` from third_party/espressif-svd/esp32c3.svd
// (sha256 abc123). Do not edit.
// Register data: Copyright Espressif Systems (Shanghai) Co., Ltd., Apache-2.0 (espressif/svd).
use crate::RegisterInfo;

pub(crate) static REGISTERS: [RegisterInfo; 2] = [
    RegisterInfo { addr: 0x6000_0000, peripheral: \"UART0\", name: \"FIFO\", reset_value: 0x0000_0000, reset_explicit: false },
    RegisterInfo { addr: 0x6000_001c, peripheral: \"UART0\", name: \"STATUS\", reset_value: 0xe000_c000, reset_explicit: true },
];
";
        assert_eq!(out, expected);
    }
}
